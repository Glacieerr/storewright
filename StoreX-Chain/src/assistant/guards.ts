/**
 * 值班助手的几道护栏（在意图分类之前、按明确的规则判断，优先于分类模型）：
 *
 * 1. 动作方向：批准还是否决按说法定。否定说法先认（不批、别批、不能批、不同意、不通过、驳回、打回、拒绝、否掉……），
 *    认过的部分拿掉以后再找批准的说法（批准、批了、同意、通过、没问题、照办、执行、拍板……）；「行不行」「能不能」这类正反问不算。
 *    两种都有、或者一种都没有又像是要处理建议卡的，先问清楚；绝不提议和问的相反的动作。
 * 2. 角色声明：「我是经理」「我代表站长」「领导授权了」「管理员说可以」「出了事我担着」「回头补签」不改变提问人的角色
 *    （角色按面板上选的）；带着这类说法要执行、批准的，按规则表拒绝并说明。
 * 3. 超出范围：和物流运营无关的事（订机票、酒店、会议室，写帖子、文案、邮件，打电话、发消息，闲聊，吃喝推荐，删改记录……），
 *    问题里出现了业务词也一样，说明能做什么。
 * 4. 指代缺了东西：「那个柜子」「那个货」「那个门」又没说是哪一个、上文也没有，先问清楚。
 */
export type Direction = 'approve' | 'reject' | 'unclear';

const NEUTRAL = /(行不行|可不可以|能不能|同不同意|批不批|要不要|好不好|是不是|该不该|批没批|有没有批)/g;
const REJECT = /(否决|否了|否掉|驳回|拒绝|打回|撤回|不同意|不行|不可以|不能批|不要批|不准批|别批|不批|别通过|不通过|不能通过|别执行|不执行|不能执行|先不处理|不用管|不用处理|不予批准|不予通过)/g;
const APPROVE = /(批准|批了|批吧|批掉|批一下|给批|准了|可以批|可以执行|同意|通过|没问题|没啥问题|没什么问题|照办|执行|拍板|就这么办|按推荐|就按|派救援|通知门店|改到空闲|追加补货|改直送)/;

/** 问待处理的建议卡（等我拍板的、待批的、要批的、还没处理的……）：这里的「拍板」「批」是修饰语，不是要动手 */
export const PENDING_ASK = /(等(着)?(我|你|人|领导|站长|经理|上级)?.{0,3}(拍板|批|审批|审|决定|处理|确认)的|待(批|审批|审|处理|决定|确认|拍板)的?|要(我|人)?(批|审批|审|处理|确认|拍板)的|需要.{0,3}(批|审批|审|确认|拍板)的|(还)?没(批|处理|确认|拍板)的)/;
/** 问的是有哪些、有没有、几张（而不是要处理某一张） */
export const LIST_ASK = /(有哪些|有没有|有什么|几张|哪几张|哪些|列一下|列出来|看看|多少张|还有)/;

/** 问题里要的动作方向：批准、否决、两种都有（要问清楚）；都没有返回 undefined */
export function actionDirection(q: string): Direction | undefined {
  const s = q.replace(new RegExp(PENDING_ASK.source, 'g'), '，').replace(NEUTRAL, '，');
  const rej = REJECT.test(s);
  REJECT.lastIndex = 0;
  const app = APPROVE.test(s.replace(REJECT, '，'));
  REJECT.lastIndex = 0;
  if (rej && app) return 'unclear';
  if (rej) return 'reject';
  if (app) return 'approve';
  return undefined;
}

