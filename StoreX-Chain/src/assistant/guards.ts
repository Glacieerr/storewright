/** 指代了一个东西又没说是哪一个：柜子 / 集装箱、货 / 商品、门 */
export function missingItem(q: string): 'container' | 'product' | 'door' | undefined {
  if (/(那个|这个|那只|这只|那批|这批|那些|该)(集装箱|箱子|箱(?!数))/.test(q)) return 'container';
  if (/(那个|这个|那批|这批|那种|这种|该)(货|商品|东西|品)/.test(q) && /(还剩|剩多少|剩下|库存|够不够|还有多少|多少|卖完)/.test(q)) return 'product';
  if (/(那个|这个|那扇|这扇|该|那)门(?!店)/.test(q)) return 'door';
  return undefined;
}
