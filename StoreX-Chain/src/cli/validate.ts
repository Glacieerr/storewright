import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runValidation, validationMarkdown, validationSummary } from '../validate';
import { checkSolution, parseSol, parseVrp, solveExact } from '../validate/cvrp';

/**
 * 对照验证：npm run validate [-- --quick] [--write]；npm run validate -- check <例子.vrp> <解.sol>（核对别的求解器的结果）
 *   --quick  小一点的样本（几秒钟），给持续集成和测试用
 *   --write  写 bench/validation/results.json、bench/validation/cvrp/*.vrp|*.sol，并更新 docs/08-validation.md 和 .en.md 里自动生成的部分
 */
const args = process.argv.slice(2);
if (args[0] === 'check') {
  // 核对别的求解器的结果：npm run validate -- check <例子.vrp> <解.sol>
  const [, vrp, sol] = args;
  if (!vrp || !sol) {
    process.stderr.write('usage: npm run validate -- check <instance.vrp> <solution.sol>\n');
    process.exit(2);
  }
  const inst = parseVrp(readFileSync(vrp, 'utf8'));
  const s = parseSol(readFileSync(sol, 'utf8'));
  const errs = checkSolution(inst, s);
  const best = inst.xy.length <= 15 ? solveExact(inst).cost : undefined;
  process.stdout.write(`${inst.name}: ${errs.length ? `INVALID — ${errs.join('; ')}` : `valid, cost ${s.cost}`}${best !== undefined ? `; optimum ${best}${errs.length ? '' : `, gap ${(((s.cost - best) / best) * 100).toFixed(2)}%`}` : ''}\n`);
  process.exit(errs.length ? 1 : 0);
}
const quick = args.includes('--quick');
const t0 = performance.now();
const r = runValidation({ quick });
process.stdout.write(`${validationSummary(r)}\n(${((performance.now() - t0) / 1000).toFixed(1)} s${quick ? ', quick' : ''})\n`);

if (args.includes('--write')) {
  const root = (p: string) => fileURLToPath(new URL(`../../${p}`, import.meta.url));
  mkdirSync(root('bench/validation/cvrp'), { recursive: true });
  for (const x of r.library) {
    writeFileSync(root(`bench/validation/cvrp/${x.name}.vrp`), x.vrp);
    writeFileSync(root(`bench/validation/cvrp/${x.name}.sol`), x.sol);
  }
  const { library, ...rest } = r;
  const json = { ...rest, library: library.map(({ vrp: _v, sol: _s, ...l }) => l) };
  writeFileSync(root('bench/validation/results.json'), `${JSON.stringify(json, (k, v) => (typeof v === 'number' && !Number.isInteger(v) ? Math.round(v * 1e6) / 1e6 : v), 2)}\n`);
  for (const [file, lang] of [
    ['docs/08-validation.md', 'zh'],
    ['docs/08-validation.en.md', 'en'],
  ] as const) {
    const p = root(file);
    const text = readFileSync(p, 'utf8');
    const a = text.indexOf('<!-- validation:begin -->');
    const b = text.indexOf('<!-- validation:end -->');
    if (a < 0 || b < a) throw new Error(`${file}: markers not found`);
    writeFileSync(p, `${text.slice(0, a)}<!-- validation:begin -->\n<!-- 下面这几节由 npm run validate -- --write 生成，不要手改 · generated by npm run validate -- --write -->\n\n${validationMarkdown(r, lang)}\n${text.slice(b)}`);
  }
  process.stdout.write('written: bench/validation/, docs/08-validation.md, docs/08-validation.en.md\n');
}
