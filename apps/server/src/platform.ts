/**
 * 平台能力：哈希与安全随机数。服务端用 Node 的 crypto（platform.node.ts），
 * 浏览器内演示模式用 Web Crypto 的随机数和这里的纯 TypeScript SHA-256。这个文件不能引用 Node 专有的模块。
 */
export interface HubPlatform {
  sha256Hex(input: string): string;
  randomBytes(n: number): Uint8Array;
}

/** 0 ≤ 结果 < max 的均匀随机整数（拒绝采样，避免取模偏差） */
export function randomInt(p: HubPlatform, max: number): number {
  const limit = Math.floor(0x100000000 / max) * max;
  for (;;) {
    const b = p.randomBytes(4);
    const v = ((b[0] as number) << 24 >>> 0) + ((b[1] as number) << 16) + ((b[2] as number) << 8) + (b[3] as number);
    if (v < limit) return v % max;
  }
}

export function toHex(bytes: Uint8Array): string {
  let s = '';
  for (const b of bytes) s += b.toString(16).padStart(2, '0');
  return s;
}

const B64URL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
export function toBase64Url(bytes: Uint8Array): string {
  let s = '';
  for (let i = 0; i < bytes.length; i += 3) {
    const n = ((bytes[i] as number) << 16) | ((bytes[i + 1] ?? 0) << 8) | (bytes[i + 2] ?? 0);
    const chars = Math.min(4, Math.ceil(((bytes.length - i) * 8) / 6));
    for (let k = 0; k < chars; k++) s += B64URL[(n >>> (18 - 6 * k)) & 63];
  }
  return s;
}

